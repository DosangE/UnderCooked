// Interact 한 번의 결과 묶음.
// KitchenEnv.TryInteract가 돌려주고, ChefAgent가 보상 계산에 쓴다.
public struct InteractOutcome
{
    public InteractResult Result;

    // 상호작용 후 손에 남는 것.
    public ItemType NewHeldItem;

    // 그 물건이 **이미 전달 보상을 받은 적이 있는가.**
    //
    // 같은 물건을 카운터로 왕복시키는 것만으로 보상을 긁는 것을 막으려면 물건마다
    // 이 기록이 따라다녀야 한다. ItemType은 enum이라 개체 구분이 없으므로,
    // 손과 카운터가 이 플래그를 같이 들고 다닌다.
    //
    // 손질대나 냄비를 거치면 '다른 물건'이 되므로 false로 돌아간다.
    // 그래야 정상 파이프라인(생재료 -> 손질 -> 전달 -> 냄비 -> 요리 -> 전달 -> 서빙)의
    // 전달 두 번은 그대로 보상받는다.
    public bool NewItemTransferred;

    // 그 물건에 딸린 '되돌릴 수 있는 진행 보상'의 합.
    //
    // 손질/투입으로 지급된 팀 보상은 서빙으로 이어졌을 때만 정당하다. 그래서 냄비가
    // 들고 있던 크레딧이 완성 요리에 옮겨 붙고, 카운터를 건너 동료에게까지 따라간다.
    // 제대로 서빙되면 확정되고, 주문에 없는 요리를 내거나 버리면 그때 회수한다.
    public float NewItemCredit;

    // 그 물건에 딸린 '되돌릴 수 있는 전달 보상'. 셰프 **한 명당** 금액이다.
    //
    // 전달 보상(+0.15)은 놓은 쪽과 집은 쪽 둘 다에게 개인 보상으로 나간다. 진행 보상과
    // 같은 이유로 서빙이 무산되면 되돌려야 한다 - 아니면 '전달 -> 냄비 -> 비우기'나
    // '그릇 전달 -> 되받아 버리기'가 서빙 없이 개인 보상을 쌓는다 (README 4-19).
    // 회수도 **개인 보상에서** 한다. 커리큘럼 임계값은 개인 보상만 보기 때문이다.
    public float NewItemTransferCredit;

    // 카운터에서 '동료가 놓은' 물건을 집었을 때 그 동료의 인덱스. 그 외에는 -1.
    // 전달 보상(+0.15)을 놓은 쪽에도 소급해서 주기 위해 필요하다.
    public int TransferPartnerIndex;
}
