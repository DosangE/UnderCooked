// 그리드 위 상호작용 지점의 종류.
//
// 값은 프리팹의 Station 컴포넌트에 직렬화되어 있으므로 기존 번호를 바꾸지 않는다.
// (이름만 바꾸는 것은 안전하다. Unity는 enum을 int로 저장한다)
//
// 재료함 두 개는 카운터 경계 위에 있어 양쪽 구역에서 모두 집을 수 있다.
// 대신 냄비가 A 구역, 그릇함/서빙구가 B 구역에 있어서 협동은 그쪽에서 강제된다.
//
// 손질대는 '색'이 아니라 '구역'으로 나뉜다 (6=A구역, 7=B구역).
// 예전에는 초록 손질대 / 빨강 손질대였는데, 그러면 재료의 색과 담당 구역이 묶여서
// 주문이 색을 정하는 순간 담당자까지 정해져 버렸다. RedSoup(빨강x2) 주문에서는
// B가 이동량의 81%를 지고 A는 냄비 앞에서 받기만 하는 4.3:1 쏠림이 났다.
// (tools/measure_reach.py 참조)
public enum StationType
{
    GreenBox = 0,      // 초록 재료함 (경계, 공용)
    Pot = 1,           // 냄비      (A 구역)
    PlateStack = 2,    // 그릇함    (B 구역)
    ServingHatch = 3,  // 서빙구    (B 구역)
    Counter = 4,       // 카운터 전달칸 (경계, 공용)
    RedBox = 5,        // 빨강 재료함 (경계, 공용)
    PrepA = 6,         // A 구역 손질대 (아무 생재료나 받는다)
    PrepB = 7          // B 구역 손질대 (아무 생재료나 받는다)
}
